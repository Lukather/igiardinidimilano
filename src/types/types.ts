/**
 * Core types for I Giardini di Milano
 * 
 * The photo is the primary unit of content. Each photo carries its own metadata.
 * There is no "garden" or "space" entity in v1 - spaces are just textual tags.
 */

// ============================================================================
// CATEGORIES
// ============================================================================

/**
 * Category of a photo - describes what the photo shows, not a judgment.
 * 
 * Definitions (from spec):
 * - in degrado: at least ONE visible sign: trash, dead plants, broken equipment, 
 *   dangerous pavement, stagnant water
 * - curato: absence of all degradation signs
 * 
 * Note: "erba alta" (tall grass) alone is NOT enough for "in degrado"
 * (naturalistic meadows are maintenance, not abandonment)
 */
export type PhotoCategory = 'curato' | 'in degrado';

/** All valid photo categories */
export const PHOTO_CATEGORIES: PhotoCategory[] = ['curato', 'in degrado'];

// ============================================================================
// COORDINATES
// ============================================================================

/**
 * Geographic coordinates with validation for Milan area.
 * 
 * Milan bounding box (approximate):
 * - Min: 45.35, 8.95
 * - Max: 45.55, 9.30
 */
export interface Coordinates {
  latitude: number;
  longitude: number;
}

/** Milan bounding box for coordinate validation */
export const MILAN_BOUNDS = {
  minLatitude: 45.35,
  maxLatitude: 45.55,
  minLongitude: 8.95,
  maxLongitude: 9.30,
};

// ============================================================================
// PHOTO METADATA
// ============================================================================

/**
 * Photo metadata - the unit of content in v1.
 * 
 * All fields are required. The build will fail if any are missing or invalid.
 */
export interface Photo {
  /**
   * Unique identifier for the photo.
   * Format: YYYY-MM-DD-slug (e.g., "2024-01-15-parco-sempione-01")
   */
  id: string;
  
  /**
   * Category describing what the photo shows.
   */
  category: PhotoCategory;
  
  /**
   * GPS coordinates where the photo was taken.
   * Must be within Milan bounds and manually confirmed.
   */
  coordinates: Coordinates;
  
  /**
   * Date when the photo was taken.
   * Format: YYYY-MM-DD
   */
  date: string;
  
  /**
   * Human-readable description of what the photo shows.
   * Should be factual and neutral (documentary tone).
   */
  description: string;
  
  /**
   * Name of the green space (park, garden, etc.).
   * This is a textual tag, not a structured entity.
   * Multiple photos can have the same space name.
   */
  space: string;
  
  /**
   * Filename of the optimized image (without path).
   * The actual file is stored in src/photos/
   */
  imageFile: string;
}

// ============================================================================
// SITE STATS
// ============================================================================

/**
 * Aggregated statistics for the site, calculated at build time.
 */
export interface SiteStats {
  totalPhotos: number;
  curatedSpaces: number;
  degradedSpaces: number;
}

// ============================================================================
// BUILD ARTIFACTS
// ============================================================================

/**
 * The complete data structure used by the frontend.
 * Generated by the build script.
 *
 * The file is versioned and must be reproducible byte for byte: same input
 * photos, same output file. Nothing in here may come from the clock.
 */
export interface SiteData {
  /**
   * Photos sorted newest first, ties broken by ID ascending.
   * The order is part of the contract: the hero picks the first photo of
   * each category, so a stable order means a stable hero.
   */
  photos: Photo[];
  stats: SiteStats;
  /**
   * Date (YYYY-MM-DD) of the most recent photo, derived from the data.
   * Not a build timestamp: that would make every build dirty the repo.
   */
  latestPhotoDate: string;
}
